# ⚠ 第一版写成 `\(Entry\s+([\d\s·]+)\)` —— **要求右括号紧跟数字**,于是漏掉 4 行:
#   `(Entry 642 · 711 / ...)` 这种括号里还有别的内容的,以及行内提到 `Entry 679` 的。
#   4/93 ≈ 4%,**而「结构定总体」的全部价值就在于召回按构造 = 1** —— 漏 4 行就不是按构造了。
#   ⇒ 放宽成「`(Entry` 后面跟数字」即可,不要求右括号紧邻。**这一条是本轮自己的完整性检查抓到的。**
ROW = re.compile(r"^\|\s*(.+?)\s*\|.*\(Entry\s+(\d[\d\s·]*)")

def claims(path):
    out = []
    for i, line in enumerate(path.read_text(encoding="utf-8").split("\n"), 1):
        m = ROW.match(line)
        if not m: continue
        out.append(dict(line=i, claim=re.sub(r"[*`~]", "", m.group(1)).strip(),
                        entries=[int(x) for x in re.findall(r"\d+", m.group(2))]))
    return out

print("=== ① 结构定总体:主表里每一行都以 `(Entry N)` 结尾 —— 枚举它,召回按构造 = 1 ===")
Z = claims(ROOT/"README_zh.md")
