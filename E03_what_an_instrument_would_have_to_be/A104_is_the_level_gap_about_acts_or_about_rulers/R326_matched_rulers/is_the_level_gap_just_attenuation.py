def sim_pair(rho_t, rel_x, rel_y, n, rng):
    z = rng.standard_normal(n)
    x = rho_t * z + np.sqrt(max(1e-9, 1 - rho_t ** 2)) * rng.standard_normal(n)
    y = z
    xo = np.sqrt(rel_x) * x + np.sqrt(max(1e-9, 1 - rel_x)) * rng.standard_normal(n)
    yo = np.sqrt(rel_y) * y + np.sqrt(max(1e-9, 1 - rel_y)) * rng.standard_normal(n)
    r = stats.spearmanr(xo, yo).statistic
    return 1 - r ** 2


